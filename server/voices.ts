export function resolveCloneBaseEdgeVoice(
  targetLang: string,
  gender: 'Male' | 'Female'
): string {
  const pair = CLONE_EDGE_MAP[targetLang] ?? CLONE_EDGE_MAP.en;
  return gender === 'Female' ? pair.female : pair.male;
}

export function resolveVoice(identifier?: string): VoicePersona {
  if (!identifier) {
    return VOICE_CATALOG[0];
  }
  const found = VOICE_CATALOG.find(
    (v) => v.id === identifier || v.elevenlabsVoiceId === identifier
  );
  return found ?? VOICE_CATALOG[0];
}

export function getLanguageLabel(code: string): string {
  const found = SUPPORTED_LANGUAGES.find((l) => l.code === code);
  return found ? found.label : code;
}
